// `sbd deploy`: copies the scaffolds `planScaffold` reports. The generator header of each
// deployed file gains the template's checksum, in the format agents/scaffold-generator.md
// uses, so a later run can tell an untouched scaffold (safe to update) from one the user
// edited or wrote (left alone unless --force).
import { createHash } from 'node:crypto';
import { lstatSync, mkdirSync, readFileSync, writeFileSync, type Stats } from 'node:fs';
import { dirname } from 'node:path';
import { assetPath } from './assets.js';
import { planScaffold, resolveStack, type ScaffoldPlanItem } from './controls.js';
import { confine, resolvesInside } from './paths.js';
import type { Manifest } from './types.js';
import { VERSION } from './version.js';

export type DeployState =
  | 'missing' // nothing at the target
  | 'current' // deployed from this template, not edited
  | 'outdated' // deployed from an older template, not edited
  | 'edited' // deployed by sbd, changed since
  | 'user-authored' // no stamp: not written by sbd deploy
  | 'elsewhere' // the scaffold exists under another accepted name
  | 'unsafe-path' // a symlink or non-file at the target, or the path leaves the root
  | 'no-template'; // this stack has no template for the scaffold

export type DeployAction = 'create' | 'update' | 'overwrite' | 'none' | 'skip' | 'blocked';

export interface DeployItem {
  ruleId: string;
  title: string;
  target: string;
  template: string;
  state: DeployState;
  action: DeployAction;
  presentAt?: string;
  detail?: string;
}

export interface DeployPlan {
  stack: string;
  force: boolean;
  items: DeployItem[];
  summary: Record<DeployAction, number>;
}

const GENERATED = 'Generated by secure-by-design';
const HEADER_LINES = 5;
const CHECKSUM = /^(?:\/\/|#) Template checksum: sha256-([0-9a-f]{64})$/;

// Line endings are normalised so a checkout with autocrlf does not read as an edit.
const lf = (text: string) => text.replace(/\r\n/g, '\n');
const sha256 = (text: string) => createHash('sha256').update(text).digest('hex');

/** The template with its checksum on the line after the generator header. */
function stamped(template: string, text: string): string {
  const comment = template.endsWith('.py') ? '#' : '//';
  const name = template.replace(/^templates\//, '');
  const lines = text.split('\n');
  const header = lines.slice(0, HEADER_LINES).findIndex((l) => l.includes(GENERATED));
  const stamp = `${comment} Template checksum: sha256-${sha256(lf(text))}`;
  if (header === -1) return `${comment} ${GENERATED} from ${name}.\n${stamp}\n${text}`;
  lines.splice(header + 1, 0, stamp);
  return lines.join('\n');
}

/** The checksum in a file's header, and the hash of the file without that line. */
function readStamp(text: string): { recorded: string; actual: string } | undefined {
  const lines = lf(text).split('\n');
  const at = lines.slice(0, HEADER_LINES + 1).findIndex((l) => CHECKSUM.test(l));
  if (at === -1) return undefined;
  const [line] = lines.splice(at, 1);
  // A header sbd added to a template without one is not part of the template.
  if (at === 1 && lines[0]!.includes(`${GENERATED} from `)) lines.shift();
  return { recorded: CHECKSUM.exec(line!)![1]!, actual: sha256(lines.join('\n')) };
}

function lstat(abs: string): Stats | undefined {
  try {
    return lstatSync(abs);
  } catch {
    return undefined;
  }
}

type Classified = Pick<DeployItem, 'state' | 'action' | 'detail'>;

function classify(root: string, it: ScaffoldPlanItem, force: boolean): Classified {
  const replace = (state: DeployState, detail: string): Classified =>
    force ? { state, action: 'overwrite', detail: `${detail}; replaced by --force` } : { state, action: 'skip', detail: `${detail}; --force replaces it` };
  // A symlink is never written through, even with --force: it could point outside the root.
  const unsafe = (detail: string): Classified => ({ state: 'unsafe-path', action: it.presentAt ? 'skip' : 'blocked', detail });

  if (!resolvesInside(root, it.target)) return unsafe(`${it.target} resolves outside the workspace root`);
  const st = lstat(confine(root, it.target));
  if (st && !st.isFile()) return unsafe(`${it.target} is not a regular file`);
  if (!st) {
    if (it.presentAt) return { state: 'elsewhere', action: 'skip', detail: `already present at ${it.presentAt}` };
    if (!it.templateExists) return { state: 'no-template', action: 'blocked', detail: `no template at ${it.template}` };
    return { state: 'missing', action: 'create' };
  }
  if (!it.templateExists) return { state: 'user-authored', action: 'skip', detail: `no template at ${it.template}` };

  const stamp = readStamp(readFileSync(confine(root, it.target), 'utf8'));
  if (!stamp) return replace('user-authored', 'no template checksum');
  if (stamp.actual !== stamp.recorded) return replace('edited', 'edited since deploy');
  const fresh = sha256(lf(readFileSync(assetPath(it.template), 'utf8')));
  return stamp.recorded === fresh ? { state: 'current', action: 'none' } : { state: 'outdated', action: 'update' };
}

/** What `sbd deploy` would do. Reads only. */
export function planDeploy(root: string, m: Manifest, opts: { stack?: string; force?: boolean } = {}): DeployPlan {
  const stack = resolveStack(root, m, opts.stack);
  if (!stack) throw new Error('cannot tell the stack: pass --stack or set product.stack in the manifest');
  const force = opts.force ?? false;
  const items = planScaffold(root, m, stack).map((it) => ({
    ruleId: it.ruleId,
    title: it.title,
    target: it.target,
    template: it.template,
    ...(it.presentAt ? { presentAt: it.presentAt } : {}),
    ...classify(root, it, force),
  }));
  const summary: DeployPlan['summary'] = { create: 0, update: 0, overwrite: 0, none: 0, skip: 0, blocked: 0 };
  for (const it of items) summary[it.action]++;
  return { stack, force, items, summary };
}

/** Carries out a plan. Returns the paths written, in plan order. */
export function applyDeploy(root: string, plan: DeployPlan): string[] {
  const written: string[] = [];
  for (const it of plan.items) {
    if (!['create', 'update', 'overwrite'].includes(it.action)) continue;
    const abs = confine(root, it.target);
    mkdirSync(dirname(abs), { recursive: true });
    const content = stamped(it.template, readFileSync(assetPath(it.template), 'utf8'));
    // Exclusive for new files, so a file that appeared since the plan is not replaced.
    writeFileSync(abs, content, { flag: it.action === 'create' ? 'wx' : 'w' });
    written.push(it.target);
  }
  return written;
}

export function deployText(p: DeployPlan, dryRun: boolean): string {
  const width = Math.max(...p.items.map((i) => i.target.length), 0);
  const lines = [`sbd deploy (${p.stack})${dryRun ? ': dry run, nothing written' : ''}`];
  for (const it of p.items) {
    lines.push(`  ${it.action.padEnd(9)} ${it.target.padEnd(width)}  ${it.detail ?? it.state}`);
  }
  if (!p.items.length) lines.push('  the manifest requires no scaffolds');
  const s = p.summary;
  const counts = dryRun
    ? `${s.create} to create, ${s.update} to update, ${s.overwrite} to overwrite`
    : `${s.create} created, ${s.update} updated, ${s.overwrite} overwritten`;
  lines.push('', `${counts}, ${s.none} unchanged, ${s.skip} skipped, ${s.blocked} blocked.`);
  if (s.blocked) lines.push('Blocked scaffolds are still missing: fix the path, or add a template for this stack.');
  if (!dryRun) lines.push('Next: sbd check. The scaffolds are starting points; they do not make the project compliant.');
  return lines.join('\n');
}
