// Deploys the Python scaffolds into a sample FastAPI app from `sbd plan`, then runs that app.
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { copyFileSync, cpSync, mkdirSync, mkdtempSync, readFileSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { scaffoldPython } from '../../scripts/python-env.mjs';
import { json, REPO, sbd } from './helpers.mjs';

const FIXTURE = join(REPO, 'mcp-server/test/fixtures/fastapi-app');
const CLINIC_MANIFEST = 'mcp-server/test/fixtures/clinic-app/privacy-security-manifest.yaml';

const plan = (args) => JSON.parse(sbd(['plan', ...args]).stdout);

function deployed() {
  const dir = mkdtempSync(join(tmpdir(), 'sbd-fastapi-'));
  cpSync(FIXTURE, dir, { recursive: true });
  const items = plan(['--root', dir]);
  for (const item of items) {
    mkdirSync(dirname(join(dir, item.target)), { recursive: true });
    copyFileSync(join(REPO, item.template), join(dir, item.target));
  }
  return { dir, items };
}

test('plan follows --stack, then manifest product.stack, then typescript-express', () => {
  const py = plan(['--root', REPO, '--manifest', CLINIC_MANIFEST, '--stack', 'python-fastapi']);
  assert.ok(py.length >= 10);
  for (const item of py) {
    assert.ok(item.templateExists, `${item.template} missing`);
    assert.match(item.template, /^templates\/python-fastapi\/\w+\.py$/);
    assert.match(item.target, /^src\/\w+\/\w+\.py$/);
  }
  assert.ok(plan(['--root', REPO, '--manifest', CLINIC_MANIFEST]).every((i) => i.target.endsWith('.ts')));
  assert.ok(plan(['--root', FIXTURE]).every((i) => i.target.endsWith('.py')));
  assert.ok(plan(['--root', REPO, '--manifest', CLINIC_MANIFEST, '--stack', 'typescript-nextjs']).every((i) => !i.templateExists), 'a known stack without templates shows as a gap');
  const unknown = sbd(['plan', '--root', REPO, '--manifest', CLINIC_MANIFEST, '--stack', 'go-gin']);
  assert.equal(unknown.code, 2);
  assert.match(unknown.stderr, /unknown stack go-gin/);
});

test('missing-scaffold remediation names the manifest stack', () => {
  const { findings } = json(['check', '--root', FIXTURE]);
  const f = findings.find((x) => x.ruleId === 'SBD-SCAF-001');
  assert.match(f.remediation, /templates\/python-fastapi\/consent\.py to src\/privacy\/consent\.py/);
});

test('every Python scaffold carries the generated header and no compliance claim', () => {
  const dir = join(REPO, 'templates/python-fastapi');
  for (const f of readdirSync(dir)) {
    const src = readFileSync(join(dir, f), 'utf8');
    assert.match(src, /^# Generated by secure-by-design v0\.1\.0 for /, f);
    assert.match(src, /# Safe to modify\. Safe to delete\. Re-run \/sbd-deploy to regenerate\./, f);
    assert.doesNotMatch(src, /\b(compliant|satisfies|guarantees)\b/i, f);
  }
  assert.doesNotMatch(readFileSync(join(dir, 'decision_log.py'), 'utf8'), /^\s*(from|import)\b.*phi_redaction/m);
});

test('scaffolds deployed from the plan import, type-check and run in a FastAPI app', () => {
  const { dir, items } = deployed();
  assert.equal(items.length, 11);
  const python = scaffoldPython();
  const run = spawnSync(python, ['-m', 'unittest', 'test_app'], { cwd: dir, encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
  execFileSync(python, ['-m', 'mypy', '--strict', '--python-version', '3.10', '--namespace-packages', '--explicit-package-bases', '--cache-dir', join(REPO, 'build/mypy-cache'), 'src'], { cwd: dir, stdio: 'pipe' });
});

test('sbd check accepts the deployed Python scaffolds', () => {
  const { dir } = deployed();
  const { findings } = json(['check', '--root', dir]);
  assert.deepEqual(findings.filter((f) => f.ruleId.startsWith('SBD-SCAF')), []);
  assert.deepEqual(findings.filter((f) => f.ruleId.startsWith('SBD-CODE')).map((f) => `${f.ruleId} ${f.file}:${f.line}`), []);
});
